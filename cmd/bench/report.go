// writeReport generates docs/BENCHMARKS.md from the artifacts, so every number
// in it can be traced to a file. A test with no artifact says so.
func writeReport() {
	var b strings.Builder
	fmt.Fprintf(&b, "# Benchmarks\n\nGenerated by `make report` from the files in `artifacts/`. Do not edit by hand.\n\n")
	b.WriteString(`## Method
- **One machine.** Both databases, Cuboid, the store app and the load generator share its cores and disk. The app's own numbers therefore include contention a real deployment would not have.
- **Uncached** means the request carries the operator bench header, which skips the answer cache. It still goes through the API, planner and row security.
- **Viewers** are simulated dashboards refreshing at human pace against Cuboid, with its cache on.
- **Same data and app workload** for every path. The direct baseline has the indexes and connection pooling a careful team would give it.
- Data is synthetic: ` + "`cmd/seed`" + `, with one store far larger than the rest, as the PRD describes.

`)
	var sp speedArtifact
	if readJSON("speed", "main", &sp) == nil {
		fmt.Fprintf(&b, "## Query time, main tier (T1)\nMeasured %s on %s logical CPUs, %d stores. %d viewers: p50 %.0f ms, p99 %.0f ms, %d errors.\n\n",
			sp.GeneratedAt.Format("2 January 2006 15:04"), sp.Environment["cpus"], sp.Stores, sp.Viewers, sp.ViewersP50, sp.ViewersP99, sp.ViewersErr)
		b.WriteString("| Query | Uncached p50 | Uncached p99 | Largest store p99 | Cached p99 |\n|---|---:|---:|---:|---:|\n")
		for _, r := range sp.Rows {
			fmt.Fprintf(&b, "| %s | %.1f ms | %.1f ms | %.1f ms | %.1f ms |\n", r.Query, r.Uncached.P50, r.Uncached.P99, r.Largest.P99, r.Cached.P99)
		}
		b.WriteString("\n```mermaid\nxychart-beta\n  title \"Uncached p99 by query, main tier (ms)\"\n  x-axis [")
		var names, vals []string
		for i, r := range sp.Rows {
			names = append(names, fmt.Sprintf("\"Q%d\"", i+1))
			vals = append(vals, fmt.Sprintf("%.1f", r.Uncached.P99))
		}
		fmt.Fprintf(&b, "%s]\n  y-axis \"ms\"\n  bar [%s]\n```\nQ1 to Q%d follow the table's order.\n\n", strings.Join(names, ", "), strings.Join(vals, ", "), len(sp.Rows))
	} else {
		b.WriteString("## Query time, main tier (T1)\nNo artifact. Run `make speed-test`.\n\n")
	}

	var fr freshArtifact
	if readJSON("freshness", "main", &fr) == nil {
		fmt.Fprintf(&b, "## Freshness (T2)\nFrom the store app's write to the number changing through the API. Insert p50 %.0f ms, p99 %.0f ms, max %.0f ms. Update p50 %.0f ms, p99 %.0f ms, max %.0f ms. %d timed out.\n\n",
			fr.Inserts.P50, fr.Inserts.P99, fr.Inserts.Max, fr.Updates.P50, fr.Updates.P99, fr.Updates.Max, fr.TimedOut)
	}

	var sa safetyArtifact
	if readJSON("safety", "main", &sa) == nil {
		fmt.Fprintf(&b, "## Database safety (T3)\nThe store app's own query time in each phase. Measured %s.\n\n| Phase | Dashboards | App p50 | App p95 | Slower at p95 | Slower at p50 | Dashboard p99 | Dashboard errors |\n|---|---:|---:|---:|---:|---:|---:|---:|\n",
			sa.GeneratedAt.Format("2 January 2006 15:04"))
		for _, p := range sa.Phases {
			fmt.Fprintf(&b, "| %s | %d | %.2f ms | %.2f ms | %.1f%% | %.1f%% | %.0f ms | %d |\n", p.Name, p.Viewers, p.P50, p.P95, p.SlowerP95, p.SlowerP50, p.DashP99, p.DashErrors)
		}
		fmt.Fprintf(&b, "\n%s\n\n", sa.Note)
	} else {
		b.WriteString("## Database safety (T3)\nNo artifact. Run `make safety-test`.\n\n")
	}

	var co struct {
		Tier     string `json:"tier"`
		Quiesced struct {
			Total int `json:"total"`
			Exact int `json:"exact"`
		} `json:"quiesced"`
		Live struct {
			Total int `json:"total"`
			Exact int `json:"exact"`
		} `json:"live"`
	}
	if readJSON("correctness", "main", &co) == nil {
		fmt.Fprintf(&b, "## Correctness (T4)\nRandom queries on random stores, each compared with direct SQL on the main database at the same WAL position. Quiesced: %d of %d exact. While writes ran: %d of %d exact.\n\n",
			co.Quiesced.Exact, co.Quiesced.Total, co.Live.Exact, co.Live.Total)
	}

	var gr growthArtifact
	if readJSON("growth", "latest", &gr) == nil {
		b.WriteString("## Growth, 1M to 10M orders (T5)\n| Query | Pooled p99, 1M | Pooled p99, 10M | Ratio | Largest store p99, 1M | Largest store p99, 10M | Ratio |\n|---|---:|---:|---:|---:|---:|---:|\n")
		for _, r := range gr.Rows {
			fmt.Fprintf(&b, "| %s | %.1f ms | %.1f ms | %.2fx | %.1f ms | %.1f ms | %.2fx |\n", r.Query, r.SmallP99MS, r.MainP99MS, r.UncachedP99, r.LargestP99Small, r.LargestP99Main, r.LargestRatio)
		}
		fmt.Fprintf(&b, "\n%s\n\n", gr.Note)
	}

	b.WriteString(`## Limits of these numbers
- One laptop, one run of each test. Treat small differences as noise.
- Top customers' cost grows with the customers in the range, which rollups cannot shrink. It is the slowest query and the worst growth ratio.
- Isolation and chaos totals are on the Results page and in ` + "`artifacts/`" + `, with the tier each ran at.
- ` + "`REPLICA IDENTITY FULL`" + `'s extra WAL has not been measured.
`)
	fmt.Fprintf(&b, "\nGenerated %s.\n", time.Now().Format("2 January 2006 15:04"))
	p := filepath.Join("docs", "BENCHMARKS.md")
	if err := os.WriteFile(p, []byte(b.String()), 0o644); err != nil {
		fatal(err)
	}
	fmt.Println("wrote", p)
}

// rebuildFromMain asks Cuboid to rebuild from the main database, as after
// loading the organisers' data.
func rebuildFromMain(w *world) {
	code, err := postJSON(cuboidURL+"/admin/rebuild?source=main&scope=all", w.op, nil, nil)
	if err != nil || code != 202 {
		fatal(fmt.Errorf("rebuild: %v status %d", err, code))
	}
	fmt.Println("rebuild from the main database started; follow it on /monitor")
}
