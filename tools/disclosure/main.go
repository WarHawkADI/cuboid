// Command disclosure regenerates the third-party tables in docs/DISCLOSURE.md
// from go.mod and web/package.json, reading each licence from the installed
// package. Run it after changing a dependency. Hackathon rule 1 asks for this list.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

const (
	docPath = "docs/DISCLOSURE.md"
	begin   = "<!-- generated by tools/disclosure: do not edit below -->"
	end     = "<!-- generated by tools/disclosure: do not edit above -->"
)

// goLicence names a licence from the text of its file.
func goLicence(dir string) string {
	files, _ := filepath.Glob(filepath.Join(dir, "LICEN[CS]E*"))
	more, _ := filepath.Glob(filepath.Join(dir, "COPYING*"))
	var names []string
	for _, f := range append(files, more...) {
		b, err := os.ReadFile(f)
		if err != nil {
			continue
		}
		t := string(b)
		switch {
		case strings.Contains(t, "Mozilla Public License"):
			names = append(names, "MPL-2.0")
		case strings.Contains(t, "Apache License"):
			names = append(names, "Apache-2.0")
		case strings.Contains(t, "Permission is hereby granted, free of charge"):
			names = append(names, "MIT")
		case strings.Contains(t, "Redistribution and use in source and binary forms"):
			if strings.Contains(t, "Neither the name") {
				names = append(names, "BSD-3-Clause")
			} else {
				names = append(names, "BSD-2-Clause")
			}
		}
	}
	if len(names) == 0 {
		return "check manually"
	}
	sort.Strings(names)
	return strings.Join(names, " and ")
}

func goTable() (string, error) {
	out, err := exec.Command("go", "list", "-m", "-json", "all").Output()
	if err != nil {
		return "", fmt.Errorf("go list: %w", err)
	}
	var rows []string
	dec := json.NewDecoder(bytes.NewReader(out))
	for dec.More() {
		var m struct {
			Path, Version, Dir string
			Main, Indirect     bool
		}
		if err := dec.Decode(&m); err != nil {
			return "", err
		}
		if m.Main || m.Indirect {
			continue
		}
		rows = append(rows, fmt.Sprintf("| `%s` | %s | %s |", m.Path, m.Version, goLicence(m.Dir)))
	}
	sort.Strings(rows)
	return "## Go modules (direct dependencies)\n| Module | Version | Licence |\n|---|---|---|\n" + strings.Join(rows, "\n") + "\n", nil
}

func npmTable() (string, error) {
	b, err := os.ReadFile("web/package.json")
	if err != nil {
		return "", err
	}
	var p struct{ Dependencies, DevDependencies map[string]string }
	if err := json.Unmarshal(b, &p); err != nil {
		return "", err
	}
	row := func(name, version, use string) string {
		licence := "check manually"
		if b, err := os.ReadFile(filepath.Join("web/node_modules", name, "package.json")); err == nil {
			var m struct {
				License string `json:"license"`
			}
			if json.Unmarshal(b, &m) == nil && m.License != "" {
				licence = m.License
			}
		}
		return fmt.Sprintf("| `%s` | %s | %s | %s |", name, strings.TrimPrefix(version, "^"), licence, use)
	}
	var rows []string
	for n, v := range p.Dependencies {
		rows = append(rows, row(n, v, "Shipped in the UI"))
	}
	for n, v := range p.DevDependencies {
		rows = append(rows, row(n, v, "Build and checks only"))
	}
	sort.Strings(rows)
	return "## npm packages\n| Package | Version | Licence | Use |\n|---|---|---|---|\n" + strings.Join(rows, "\n") + "\n", nil
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "disclosure:", err)
		os.Exit(1)
	}
}

func run() error {
	g, err := goTable()
	if err != nil {
		return err
	}
	n, err := npmTable()
	if err != nil {
		return err
	}
	b, err := os.ReadFile(docPath)
	if err != nil {
		return err
	}
	doc := string(b)
	block := begin + "\n" + g + "\n" + n + end + "\n"
	re := regexp.MustCompile(`(?s)` + regexp.QuoteMeta(begin) + `.*?` + regexp.QuoteMeta(end) + `\n?`)
	if !re.MatchString(doc) {
		return fmt.Errorf("%s has no generated block; add the markers", docPath)
	}
	doc = re.ReplaceAllLiteralString(doc, block)
	if err := os.WriteFile(docPath, []byte(doc), 0o644); err != nil {
		return err
	}
	fmt.Println("updated", docPath)
	return nil
}
